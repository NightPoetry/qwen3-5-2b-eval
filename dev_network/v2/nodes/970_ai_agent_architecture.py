"""知识节点：AI智能体系统架构——上下文管理、记忆系统、工作空间设计模式。

从多个AI系统设计中提炼的通用架构模式：
  - 上下文预算纪律：固定区+滑动窗口+永久记忆，三层分配不越界
  - 记忆化搜索：对话即记忆，全量保留+缓存加速，不按重要性裁剪
  - 天然刷新机制：执行决定可见性，活跃任务自然浮现
  - 工作空间哲学：内部系统(不可见)+共享桌面(可见)，共识全量加载知识按需加载
  - 上下文压缩：语义判断而非暴力截断，thinking分类保留，轮询智能合并
"""
import sys; from pathlib import Path; sys.path.insert(0, str(Path(__file__).parent.parent))
from engine import Node
from llm import ask

ARCHITECTURE_PRINCIPLES = """你是AI系统架构设计顾问。基于以下经过验证的设计模式回答问题。

## 上下文管理架构
- 三层预算分配：固定区(活跃任务,始终可见) + 滑动窗口(对话历史,自动裁剪) + 永久记忆(重要事实,按重要性裁剪)
- 预算纪律：所有存储按预算裁剪，超限时自动淘汰最旧/最低优先内容
- 共识全量加载(体积小但必须在线)，知识按需加载(可能大,渐进读取)

## 记忆系统设计
- 对话即记忆：不需要独立记忆存储，结构化对话历史是最完整的记忆源
- 记忆化搜索：借鉴动态规划，搜过的不重复搜，缓存标记加速后续检索
- 语义搜索而非关键词匹配：由LLM判断语义相关性
- 不裁剪不分级：全量保留，靠缓存加速而非缩小数据集
- 自然回忆触发：对话中自然意识到需要回忆，不是显式工具调用

## 天然刷新机制
- 执行决定可见性：执行过的任务刷新到顶部，不执行的自然沉底
- 不标记重要性：用行为表达而非标签，零维护成本
- 与人类记忆一致：经常想起的记得牢，不想的渐渐忘

## 工作空间设计
- 内部系统(AI自主维护,用户不可见) vs 工作空间(共同维护,用户完全可见)
- 讨论在先：创建目录/命名文件/归类内容，先和用户商量
- 约定记录到共识区，下次同类请求按约定执行

## 上下文压缩策略
- 语义判断而非暴力截断：每条消息分析内容类型再决定处理方式
- 完全保留：用户原始请求、文件读取原文、代码修改、用户决策
- Thinking分类：原则思考保留，执行决策去除
- 循环轮询合并：保留首次+转折点+末次，中间去除
- 错误堆栈外置：大堆栈单独存储，原位留引用标记"""

def execute(ctx: dict) -> dict:
    task = ctx.get("task", "")
    result = ask(
        ARCHITECTURE_PRINCIPLES,
        f"设计问题：{task}",
        max_tokens=300
    ).strip()
    ctx["_design_guidance"] = result
    return ctx

node = Node(id="970", name="AI智能体架构模式",
    trigger={"type": "keyword", "target": "task",
             "keywords": ["上下文管理", "记忆系统", "记忆设计", "工作空间", "context",
                          "memory", "滑动窗口", "预算", "裁剪", "压缩上下文",
                          "天然刷新", "活跃任务", "对话历史"]},
    execute=execute, refs=["Y30"],
    metadata={"source": "design/ai-agent-architecture", "category": "design"})
