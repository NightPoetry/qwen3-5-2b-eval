"""知识节点：槽位连锁机制——节点变成槽时触发的八重结构连锁。

这是认知解构理论中最深的命题之一：
  当某个节点的入边来源熵升高，MDL压力推动该节点成为参数化锚点，
  所有与之相关的子图同步重组，组合性涌现。

八重连锁：
  1.抽象节点涌现——高多样性入边的公共来源被凝聚为类型节点
  2.N个模板坍缩为1+槽——描述长度从3L降到L+|A|
  3.填充集与模板体解耦——参数化=模块化=组合性的结构基础
  4.槽成为路由竞争点——候选通过入边激活值大小排序自然竞争
  5.新填充可激活模板→泛化——跨场景边+共用拓扑的副产品
  6.子模板输出可填槽→递归组合——任意深度嵌套无须特殊机制
  7.运行时绑定状态涌现——变量赋值=槽位当前最大激活源
  8.共享抽象→跨槽同指——指代消解=共享抽象+激活持留的副产品

实用对应：
  - 软件工程中的参数化函数=降低描述长度(把可变部分独立出来形成槽)
  - 形式语法的递归在图拓扑中=子模板输出激活上层模板槽位
  - 变量作用域=激活的时间窗
"""
