"""知识节点：认知解构理论——将复杂认知任务拆解为原子操作。

理论基础（源自结构主义生成式AI四公理体系）：
  - 概念 = 节点间的连接模式（拓扑位置），不是独立实体
  - 知识 = 反复出现的稳定子图拓扑（声明性=状态共性，过程性=路径共性）
  - 理解 = 用最少前提覆盖最多现象（含可补完位置的子图拓扑）
  - 学习 = 图结构在MDL压力下的自我组织（无需反向传播）
  - 槽位 = 入边来源高度多变的节点位置（动态属性，非静态标记）
  - 2B模型的极限 = 单步连接可靠，多步串联崩溃

四条最小公理：
  公理A：有向带权图G=(V,E)，权重可正（兴奋）可负（抑制）
  公理B：激活按局部邻居规则演化，激活值有时间持留(lambda衰减)
  训练原则：图按最小描述长度(MDL)自我组织
  生成原则：激活传播→半亮拓扑识别→候选竞争→链式延展

八重结构连锁（槽位诞生触发）：
  1.抽象节点自动涌现 2.N个模板坍缩为1+槽 3.填充集与模板体解耦
  4.槽成为路由竞争点 5.新填充可激活模板(泛化) 6.子模板输出可填槽(递归组合)
  7.运行时绑定状态涌现 8.共享抽象→跨槽同指

对应到编排系统设计：
  - 每个节点 = 一个原子认知操作（单步连接）
  - 节点间连接 = 概念间关系（图的边）
  - 触发门控 = 激活阈值（MDL过滤）
  - 栈展开 = 认知链的串行激活（激活传播）
  - context传递 = 当前激活分布（上下文即位置）
"""
