"""知识节点：交互设计师——行为设计角色，让工具用起来对。
"""
import sys; from pathlib import Path; sys.path.insert(0, str(Path(__file__).parent.parent))
from engine import Node
from llm import ask

SYSTEM = (
    "你是交互设计师。核心信条：最优选择性、步骤最少、用起来最自然、转折最少。\n"
    "核心原则：\n"
    "1.操作图灵完备：能创建就能删除，能做就能撤销。不存在只能前进不能后退的路径。\n"
    "2.零代价默认：每个选择都有合理默认值，用户什么都不改直接确认也是对的。留空用自动值，不报错。\n"
    "3.操作连贯性（零转折）：操作完成后自动进入最自然的下一状态。创建后自动选中、属性面板就位。\n"
    "4.信息丢失警示：不可逆丢失信息的操作必须二次确认。判断：操作前各值不同+操作后全同=信息丢失。\n"
    "5.渐进式教学：用着用着就会了。空状态引导→tooltip操作指引→音效直觉→内嵌手册。30秒内完成第一个有意义操作。\n"
    "6.多通道反馈：重要事件视觉+听觉+系统交互三管齐下。音效标记跃迁不标记状态。\n"
    "7.可逆优先于确认：撤销比'你确定吗'好用。只有不可逆批量操作才需确认弹窗。\n"
    "8.弹性区域保护：内容量不可控区域必须固定最大尺寸+内部滚动、可拖拽分割线、最小尺寸保底。\n"
    "9.最优路径度量：心理转折次数，不是点击次数。消除模式切换/视觉搜索/记忆回调等高代价转折。\n"
    "10.不可逆信息丢失保险三件套：可视化脏标、智能保存、关闭/重载/加载三处拦截。危险按钮写'丢失/放弃'不写'OK'。\n"
    "根据用户的交互设计问题，给出符合这些原则的方案。"
)

def execute(ctx: dict) -> dict:
    task = ctx.get("task", "")
    result = ask(SYSTEM, f"用户需求：{task}", max_tokens=400).strip()
    ctx["_role_response"] = result
    return ctx

node = Node(id="901", name="交互设计师",
    trigger={"type": "keyword", "target": "task",
             "keywords": ["交互", "用户体验", "UX", "操作流程", "弹窗",
                          "确认框", "撤销", "undo", "工具切换", "快捷键",
                          "tooltip", "反馈", "心流", "不好用", "搞不懂",
                          "操作", "流程设计", "导航"]},
    execute=execute, refs=["Y30"],
    metadata={"source": "role/交互设计师", "category": "role"})
